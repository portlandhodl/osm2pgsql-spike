    /// Full decode of the real Luxembourg extract (if present): just count
    /// entities per block, no accumulation, printing totals.
    #[test]
    fn luxembourg_full_decode() {
        let path = Path::new("/tmp/opencode/luxembourg.osm.pbf");
        if !path.exists() {
            eprintln!("luxembourg.osm.pbf not present, skipping");
            return;
        }
        let start = std::time::Instant::now();
        let mut nodes = 0u64;
        let mut ways = 0u64;
        let mut blocks = 0u64;
        read_pbf_ordered(path, 4, &mut |ents| {
            blocks += 1;
            for e in &ents {
                match e {
                    Entity::Node(_) => nodes += 1,
                    Entity::Way(_) => ways += 1,
                }
            }
        });
        let dt = start.elapsed();
        println!(
            "luxembourg.osm.pbf: {blocks} blocks, {nodes} nodes, {ways} ways \
             ({} entities) decoded in {:.2?} => {:.0} entities/s",
            nodes + ways,
            dt,
            (nodes + ways) as f64 / dt.as_secs_f64()
        );
        assert!(blocks > 0);
        assert!(nodes > 0 && ways > 0, "expected both nodes and ways");
    }
